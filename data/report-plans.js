const plansByRole = new Map([
  [USER_TYPES.STUDENT, student],
  [USER_TYPES.CAREER_STARTER, starter],
  [USER_TYPES.CAREER_TRANSITION, transition],
  [USER_TYPES.CAREER_ADVISOR, advisor],
  [USER_TYPES.WORKING_PROFESSIONAL, professional]
])

function getReportPlan(userType) {
  const template = plansByRole.get(userType) || general
  return {
    label: template.label,
    objective: template.objective,
    milestones: stages.map((stage, index) => {
      const [title, action, output] = template.milestones[index]
      return { ...stage, title, action, output }
    })
  }
}

module.exports = { getReportPlan }
