function getReportPlan(userType) {
  let template = general
  if (userType === USER_TYPES.STUDENT) template = student
  if (userType === USER_TYPES.WORKING_PROFESSIONAL) template = professional

  return {
    label: template.label,
    objective: template.objective,
    milestones: stages.map((stage, index) => {
      const [title, action, output] = template.milestones[index]
      return { ...stage, title, action, output }
    })
  }
}

